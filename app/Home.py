"""
SAHAAYA Home — Statewide social-vulnerability dashboard for Tamil Nadu.

Displays KPI summary, choropleth / bar-chart map, top-risk table,
and risk-band distribution.  All data comes from the processed pipeline
outputs; if they are missing the page shows setup instructions instead.
"""
import pandas as pd
import plotly.express as px
import streamlit as st

st.set_page_config(page_title="SAHAAYA", page_icon="\U0001f5fa\ufe0f", layout="wide")

from utils import (  # noqa: E402  (must be after set_page_config)
    load_features,
    load_geojson,
    load_clusters,
    load_anomalies,
    get_data_status,
    is_mock_data,
    GEO_NAME_KEY,
    SUB_COLS,
    BAND_COLORS,
    BAND_ORDER,
)

# ---------------------------------------------------------------------------
# Title
# ---------------------------------------------------------------------------
st.title("SAHAAYA \u2014 Social Vulnerability & Early Warning")
st.caption(
    "Decision-support for exploring district-level social vulnerability "
    "in Tamil Nadu.  Scores are composite indicators, not causal claims."
)

# ---------------------------------------------------------------------------
# Sidebar — data-status panel
# ---------------------------------------------------------------------------
status = get_data_status()

with st.sidebar:
    st.subheader("Data Status")
    _icons = {True: "\u2705", False: "\u274c"}
    st.markdown(f"{_icons[status['features']]}  Features (district scores)")
    st.markdown(f"{_icons[status['clusters']]}  Cluster assignments")
    st.markdown(f"{_icons[status['anomalies']]}  Anomaly results")
    st.markdown(f"{_icons[status['geojson']]}  District boundaries (GeoJSON)")

# ---------------------------------------------------------------------------
# Load features & production guard
# ---------------------------------------------------------------------------
df = load_features()

if df is None:
    st.error("**features.parquet not found.**")
    st.info(
        "Run the data pipeline first to generate the processed data:\n\n"
        "```bash\n"
        "python -m src.run_pipeline        # or the relevant pipeline entry-point\n"
        "```\n\n"
        "The pipeline will create `data/processed/features.parquet` and other "
        "outputs that the dashboard reads."
    )
    st.stop()

if is_mock_data(df):
    st.warning(
        "\u26a0\ufe0f  **Mock / synthetic data detected.**  "
        "The current `features.parquet` appears to have been generated by "
        "`make_mock_data.py`.  Results shown below are *not* based on real "
        "government data.  Run the full pipeline to replace this file."
    )

# ---------------------------------------------------------------------------
# Period selector (use 'period' if present, fall back to 'year')
# ---------------------------------------------------------------------------
time_col = "period" if "period" in df.columns else ("year" if "year" in df.columns else None)

if time_col and df[time_col].nunique() > 1:
    periods = sorted(df[time_col].dropna().unique(), reverse=True)
    chosen = st.sidebar.selectbox("Reporting period", periods)
    view = df[df[time_col] == chosen].copy()
else:
    view = df.copy()

# ---------------------------------------------------------------------------
# Metric selector
# ---------------------------------------------------------------------------
metric_map = {"Overall": "overall_score", **SUB_COLS}
metric_label = st.sidebar.selectbox("Metric", list(metric_map.keys()))
metric_col = metric_map[metric_label]

if metric_col not in view.columns:
    st.warning(f"Column `{metric_col}` not found in data.")
    st.stop()

# ---------------------------------------------------------------------------
# KPI row
# ---------------------------------------------------------------------------
k1, k2, k3, k4 = st.columns(4)

n_districts = view["district_name"].nunique()
avg_score = view[metric_col].mean()
high_crit = (
    view["risk_band"].isin(["High", "Critical"]).sum()
    if "risk_band" in view.columns
    else "N/A"
)
completeness = (
    f"{view['data_completeness'].mean():.0%}"
    if "data_completeness" in view.columns
    else "N/A"
)

k1.metric("Districts", n_districts)
k2.metric(f"Avg {metric_label}", f"{avg_score:.1f}" if pd.notna(avg_score) else "N/A")
k3.metric("High / Critical", high_crit)
k4.metric("Data completeness", completeness)

# ---------------------------------------------------------------------------
# Main content — map + tables
# ---------------------------------------------------------------------------
left, right = st.columns([3, 2])

with left:
    geo = load_geojson()
    if geo is not None:
        fig = px.choropleth(
            view,
            geojson=geo,
            locations="district_name",
            featureidkey=GEO_NAME_KEY,
            color=metric_col,
            color_continuous_scale="YlOrRd",
            range_color=(0, 100),
            hover_data=["risk_band", "overall_score"]
            if "risk_band" in view.columns
            else ["overall_score"],
            labels={metric_col: metric_label},
        )
        fig.update_geos(fitbounds="locations", visible=False)
        fig.update_layout(margin=dict(l=0, r=0, t=30, b=0), height=600)
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.info(
            "No GeoJSON boundary file found. Showing a bar chart instead. "
            "Place `tn_districts.geojson` in `data/processed/` to enable the map."
        )
        sorted_view = view.sort_values(metric_col, ascending=True)
        fig = px.bar(
            sorted_view,
            x=metric_col,
            y="district_name",
            orientation="h",
            color=metric_col,
            color_continuous_scale="YlOrRd",
            range_color=(0, 100),
            labels={metric_col: metric_label, "district_name": "District"},
            height=max(400, len(sorted_view) * 22),
        )
        fig.update_layout(yaxis_title="", margin=dict(l=0, r=0, t=10, b=0))
        st.plotly_chart(fig, use_container_width=True)

with right:
    # --- Top-10 highest-risk ---
    st.subheader(f"Top 10 — {metric_label}")
    display_cols = ["district_name", metric_col]
    if "risk_band" in view.columns:
        display_cols.append("risk_band")

    top = (
        view.sort_values(metric_col, ascending=False)
        .head(10)[display_cols]
        .copy()
    )
    rename = {"district_name": "District", metric_col: "Score"}
    if "risk_band" in top.columns:
        rename["risk_band"] = "Band"
    top.rename(columns=rename, inplace=True)
    top["Score"] = top["Score"].round(1)
    st.dataframe(top, hide_index=True, use_container_width=True)

    # --- Risk band distribution ---
    if "risk_band" in view.columns:
        st.subheader("Risk-band distribution")
        counts = (
            view["risk_band"]
            .value_counts()
            .reindex(BAND_ORDER)
            .fillna(0)
            .astype(int)
            .reset_index()
        )
        counts.columns = ["Band", "Count"]
        fig_band = px.bar(
            counts,
            x="Band",
            y="Count",
            color="Band",
            color_discrete_map=BAND_COLORS,
            category_orders={"Band": BAND_ORDER},
        )
        fig_band.update_layout(showlegend=False, height=280)
        st.plotly_chart(fig_band, use_container_width=True)

# ---------------------------------------------------------------------------
# Bottom — data-coverage info
# ---------------------------------------------------------------------------
with st.expander("Data coverage & sources"):
    if "period" in view.columns:
        st.markdown(f"**Reporting period(s):** {', '.join(map(str, df['period'].dropna().unique()))}")
    elif "year" in view.columns:
        st.markdown(f"**Years available:** {', '.join(map(str, sorted(df['year'].dropna().unique())))}")

    # List real indicator columns (anything beyond the standard contract)
    standard = {
        "district_id", "district_name", "state", "period", "year",
        "edu_risk", "health_risk", "emp_risk", "infra_risk",
        "overall_score", "risk_band", "data_completeness",
        "cluster", "anomaly_flag", "anomaly_score", "pred_next_score",
    }
    source_cols = [c for c in df.columns if c not in standard]
    if source_cols:
        st.markdown("**Source indicators present:** " + ", ".join(f"`{c}`" for c in source_cols))
    else:
        st.markdown("No additional source indicator columns found beyond risk scores.")

    if "data_completeness" in view.columns:
        st.markdown(
            f"**Average data completeness:** {view['data_completeness'].mean():.1%} "
            f"(fraction of 4 risk dimensions available per district)"
        )
